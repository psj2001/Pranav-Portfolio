let remotePosts: BlogPost[] | null = null;

function textValue(value: unknown, max: number) {
  if (typeof value !== 'string') return '';
  return value.trim().slice(0, max);
}

function parseBlocks(value: unknown): BlogPost['body'] {
  if (!Array.isArray(value)) return [];
  const blocks: BlogPost['body'] = [];
  for (const entry of value) {
    if (!entry || typeof entry !== 'object') continue;
    const block = entry as { type?: unknown; text?: unknown; items?: unknown; src?: unknown; alt?: unknown; width?: unknown; height?: unknown };
    if (block.type === 'image') {
      const src = typeof block.src === 'string' ? block.src : '';
      const width = Number(block.width);
      const height = Number(block.height);
      if (!/^https:\/\/pranavps\.com\/api\/uploads\/posts\/(?:software|marketing)\/[a-z0-9]+(?:-[a-z0-9]+)*\/[a-f0-9]{8}\.(?:jpg|png|webp)$/.test(src)) continue;
      if (!Number.isInteger(width) || !Number.isInteger(height) || width < 1 || height < 1) continue;
      blocks.push({ type: 'image', src, alt: textValue(block.alt, 160) || 'Blog image', width, height });
      continue;
    }
    if (block.type === 'paragraph' || block.type === 'heading') {
      const text = textValue(block.text, 8000);
      if (text) blocks.push({ type: block.type, text });
      continue;
    }
    if (block.type !== 'list' || !Array.isArray(block.items)) continue;
    const items = block.items
      .filter((item): item is string => typeof item === 'string')
      .map((item) => item.trim())
      .filter(Boolean)
      .map((item) => item.slice(0, 500));
    if (items.length) blocks.push({ type: 'list', items });
  }
  return blocks;
}

/** Published posts from the API replace the built-in notes. A failed load leaves those notes in place. */
export function applyRemotePosts(data: unknown) {
  if (!Array.isArray(data)) return;
  const posts = data.flatMap((item) => {
    if (!item || typeof item !== 'object') return [];
    const post = item as BlogPost & { status?: unknown };
    if (post.status === 'review') return [];
    if (post.track !== 'software' && post.track !== 'marketing') return [];
    if (typeof post.slug !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(post.slug)) return [];
    const title = textValue(post.title, 180);
    const excerpt = textValue(post.excerpt, 2000);
    if (!title || !excerpt || typeof post.date !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(post.date)) return [];
    const body = parseBlocks(post.body);
    if (!body.length) return [];
    const minutes = Number(post.readingMinutes);
    const tags = Array.isArray(post.tags)
      ? post.tags
          .filter((tag): tag is string => typeof tag === 'string')
          .map((tag) => tag.trim())
          .filter(Boolean)
          .slice(0, 12)
      : [];
    return [
      {
        track: post.track,
        slug: post.slug,
        title,
        excerpt,
        date: post.date,
        readingMinutes: Number.isInteger(minutes) && minutes > 0 ? minutes : 1,
        tags,
        body,
      },
    ];
  });
  if (data.length > 0 && posts.length === 0) return;
  remotePosts = posts;
}

function postSource() {
  return remotePosts ?? BLOG_POSTS;
}

export function postsForTrack(track: BlogTrack) {
  return postSource()
    .filter((post) => post.track === track)
    .sort((a, b) => b.date.localeCompare(a.date));
}

export function findPost(track: BlogTrack, slug: string) {
  return postSource().find((post) => post.track === track && post.slug === slug);
}

export function formatBlogDate(iso: string) {
  return new Date(`${iso}T00:00:00`).toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  });
}
